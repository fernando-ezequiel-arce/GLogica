package micropatrones;


public class MinimoYMaximo {

		    private int min;
		    private int max;

		    public MinimoYMaximo(int min, int max) {
		        this.min = min;
		        this.max = max;
		    }

		    public int getMin() 
		    { return min; }
		    public int getMax() 
		    { return max; }
		}
